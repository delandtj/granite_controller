#!/usr/bin/env python3
"""Generate the PP-48 plane schematic for N columns (KiCad 10, hierarchical).

usage: gensch.py [N] [out.kicad_sch]   (N = 2, 4, 6 or 8 columns, default 2)

docs/adr/0004-plane-column-layout.md. The root sheet holds one sheet symbol
per column (Column 1..N, ONE file sheets/column.kicad_sch instantiated N
times, references +100 per column), a label at every sheet pin and the
power anchors. Column n's SDA / SCL are the root nets COLn_SDA / COLn_SCL:
TCA9548A channel n-1 in the core. Core sheets (one instance each, above
the columns): MCU, Mux, Link, Supplies; the tile input (hot-swap) and the
end cap are not drawn yet. The .kicad_sch
files are output, not source: edit the Python and regenerate. Engine:
tools/sch (copied from power/pp-48-2s, docs/adr/0002, plus Block.tie).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from sch import kicad as K                      # noqa: E402
from sch.draw import renumber                   # noqa: E402
from sch.blocks import column, mcu, mux, link, supplies   # noqa: E402

N = int(sys.argv[1]) if len(sys.argv) > 1 else 2
if N not in (2, 4, 6, 8):
    raise SystemExit("N must be 2, 4, 6 or 8")
PROJ_DIR = os.path.dirname(HERE)
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(PROJ_DIR, "pp-48.kicad_sch")
PROJECT = "pp-48"
DATE = "2026-10-28"
SHEETS = "sheets"
STUB = 7.62
W = 50.8
PITCH = 88.9
PER_ROW = 4
PAPERS = [("A3", 420.0, 297.0), ("A2", 594.0, 420.0), ("A1", 841.0, 594.0), ("A0", 1189.0, 841.0)]
POWER_LIB = {"GND": "power:GND", "+3V3": "power:+3V3", "VBUS": "power:VBUS", "VIN": "power:VBUS",
             "CTRL_3V3": "power:+3V3", "CTRL_GND": "power:GND", "CTRL_12V": "power:+12V"}

root = K.Sheet("Root", PROJECT, key=PROJECT + "/root", paper="A3", root=True,
               title="PP-48-%dC power plane" % N, date=DATE, rev="0.1", company="Granite",
               comments=["48 V plane, %d identical columns: LM5069-2 + INA238 + TCA9535 + ID ADC per column, screwed PM-19V-250W module" % N,
                         "generated by tools/gensch.py; docs/adr/0004-plane-column-layout.md, 0003, 0002",
                         "core: MCU, mux, link, 3V3, isolated 12 V (interim module); tile hot-swap and end cap not drawn yet"])
_pwr = [9000]
extent = [0.0, 0.0]


def seen(x, y):
    extent[0] = max(extent[0], x); extent[1] = max(extent[1], y)


def power_symbol(net, x, y, flag=False):
    _pwr[0] += 1
    if flag:
        s = K.Symbol("#FLG%d" % _pwr[0], "power:PWR_FLAG", "PWR_FLAG", "", (x, y), power=True)
    else:
        s = K.Symbol("#PWR%d" % _pwr[0], POWER_LIB.get(net, "power:" + net), net, "", (x, y), power=True)
    root.symbol(s)


def anchor(net, x, y, flag=True):
    """power symbol, global label and PWR_FLAG on one short wire (the net's ERC driver;
    no flag on nets a part drives)"""
    power_symbol(net, x, y)
    root.wire((x, y), (x + (7.62 if flag else 3.81), y), net)
    root.glabel(net, x + 3.81, y, 90)
    if flag:
        power_symbol(net, x + 7.62, y, flag=True)
    seen(x + 7.62, y + 10)


def place(name, file, blk, at, page, label):
    """sheet symbol for a finished block; label(port name) -> root net"""
    pos = {}
    for net, shape, xy, ang in blk.hlabels:
        pos.setdefault(net, xy)
    sides = {"left": [], "right": [], "top": [], "bottom": []}
    for p in blk.ports:
        sides[p["side"]].append(p)
    for side in sides:
        sides[side].sort(key=lambda p: (pos[p["name"]][1], pos[p["name"]][0]))
    rows = max(len(sides["left"]), len(sides["right"]), 1)
    h = 2.54 * (rows + 2)
    pins = [(p["name"], p["shape"], side, 2.54 * (i + 1)) for side in sides for i, p in enumerate(sides[side])]
    ss = K.SheetSymbol(name, file, at, (W, h), pins, page=page)
    root.sheet(ss)
    for side in ("left", "right"):
        for p in sides[side]:
            x, y = ss.pin_xy(p["name"])
            dx, ang = (-STUB, 180) if side == "left" else (STUB, 0)
            net = label(p["name"])
            root.wire((x, y), (x + dx, y), net)
            root.label(net, x + dx, y, ang)
    seen(at[0] + W + STUB + 20, at[1] + h + 10)
    return ss


def pwr_only(base):
    """renumber only the power symbols (+base), keep the part references"""
    return lambda ref: renumber(ref, base) if ref.startswith("#") else ref


X0, Y0 = 38.1, 38.1
row_h = 0.0
page = 2
for i, (name, fname, cb, base) in enumerate([("MCU", "mcu", mcu, 3000), ("Mux", "mux", mux, 4000),
                                             ("Link", "link", link, 5000), ("Supplies", "supplies", supplies, 6000)]):
    b = cb.block(N)
    ss = place(name, "%s/%s.kicad_sch" % (SHEETS, fname), b, (X0 + PITCH * i, Y0), page, lambda n: n)
    row_h = max(row_h, ss.size[1])
    b.write(os.path.join(PROJ_DIR, SHEETS, fname + ".kicad_sch"), instances=[(ss.path, pwr_only(base))], project=PROJECT)
    page += 1
Y0 += row_h + 30.48
blk = column.block()
paths = []
for c in range(1, N + 1):
    col, row = (c - 1) % PER_ROW, (c - 1) // PER_ROW
    ss = place("Column %d" % c, "%s/column.kicad_sch" % SHEETS, blk, (X0 + PITCH * col, Y0 + 30.48 * row), page + c - 1,
               lambda name, c=c: "COL%d_%s" % (c, name))
    paths.append((ss.path, 100 * c))
blk.write(os.path.join(PROJ_DIR, SHEETS, "column.kicad_sch"), instances=paths, project=PROJECT)

ay = round((extent[1] + 15.24) / 1.27) * 1.27
root.text("POWER ANCHORS", X0, ay - 5.08)
for i, net in enumerate(["GND", "+3V3", "VBUS", "VIN", "CTRL_3V3", "CTRL_GND", "CTRL_12V"]):
    anchor(net, X0 + 38.1 * i, ay, flag=net not in ("CTRL_GND", "CTRL_12V"))   # driven by the 12 V module U2
root.text("COLn_SDA / COLn_SCL: TCA9548A channel n-1 (Mux sheet). VIN = bus ahead of the tile hot-swap (not drawn yet)", X0, ay + 15.24, size=1.5)

for name, wmm, hmm in PAPERS:
    if extent[0] + 10 <= wmm and extent[1] + 25 <= hmm:
        root.paper = name
        break
root.write(OUT)
print("wrote", OUT, "columns", N, "paper", root.paper)

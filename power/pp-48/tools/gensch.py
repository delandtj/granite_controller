#!/usr/bin/env python3
"""Generate the chained PP-48 plane schematics (KiCad 10, hierarchical).

usage: gensch.py core|unit [project dir]

docs/adr/0005-chained-plane-boards.md: two board designs, each its own KiCad
project next to this one (default power/pp-48-core, power/pp-48-unit); the
engine, blocks, pp.kicad_sym and pp48.pretty stay in power/pp-48 and are
shared.

core: sheets Input (XT30, TVS, caps, VIN_SNS), Supplies, MCU (no TILE_*
pins), Mux, Link, Chain (OUT header, Pk = mux channel k). Root nets
UNITk_SDA / SCL = mux channel k-1 = chain Pk-1.
unit: sheets Unit (two slots, TCA6424A; refs as drawn, slot B +50), Input
(XT60, unit hot-swap, INA238 0x44; refs 2xx), Chain (IN / OUT headers, J301 /
J302). Root nets SEG_SDA / SEG_SCL (this unit's segment = chain IN P0),
U_OFF / U_PGD (expander P13 / P27 to the unit hot-swap).

The .kicad_sch files are output, not source: edit the Python and
regenerate. The single-board rev1 (core + units on one PCB, ADR 0004) is at
tag pp48-rev1.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from sch import kicad as K                      # noqa: E402
from sch.draw import renumber                   # noqa: E402
from sch.blocks import unit, mcu, mux, link, supplies, chain, cinput, uinput   # noqa: E402

KIND = sys.argv[1] if len(sys.argv) > 1 else ""
if KIND not in ("core", "unit"):
    raise SystemExit("usage: gensch.py core|unit [project dir]")
PROJECT = "pp-48-" + KIND
PROJ_DIR = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.dirname(HERE)), PROJECT)
OUT = os.path.join(PROJ_DIR, PROJECT + ".kicad_sch")
DATE = "2026-10-29"
SHEETS = "sheets"
STUB = 7.62
W = 50.8
PITCH = 88.9
PAPERS = [("A3", 420.0, 297.0), ("A2", 594.0, 420.0), ("A1", 841.0, 594.0), ("A0", 1189.0, 841.0)]
POWER_LIB = {"GND": "power:GND", "+3V3": "power:+3V3", "VBUS": "power:VBUS", "VIN": "power:VBUS",
             "CTRL_3V3": "power:+3V3", "CTRL_GND": "power:GND", "CTRL_12V": "power:+12V"}

if KIND == "core":
    TITLE = "PP-48 core board"
    COMMENTS = ["chained plane core: XT30 input, 3V3 buck, isolated 12 V aux, STM32G070, TCA9548A, RS-485 link",
                "chain OUT (JST PH 12): Pk = mux channel k, 3V3 to the units; docs/adr/0005-chained-plane-boards.md",
                "generated by tools/gensch.py core (power/pp-48/tools)"]
else:
    TITLE = "PP-48 unit board"
    COMMENTS = ["chained plane unit: two slots (LM5069-2 + INA238 + ID ADC each), TCA6424A, unit hot-swap LM5069-1 + INA238",
                "XT60 input, chain IN / OUT (JST PH 12, rotating channel); docs/adr/0005-chained-plane-boards.md, 0004",
                "generated by tools/gensch.py unit (power/pp-48/tools)"]
root = K.Sheet("Root", PROJECT, key=PROJECT + "/root", paper="A3", root=True,
               title=TITLE, date=DATE, rev="0.1", company="Granite", comments=COMMENTS)
_pwr = [9000]
extent = [0.0, 0.0]


def seen(x, y):
    extent[0] = max(extent[0], x); extent[1] = max(extent[1], y)


def power_symbol(net, x, y, flag=False):
    _pwr[0] += 1
    if flag:
        s = K.Symbol("#FLG%d" % _pwr[0], "power:PWR_FLAG", "PWR_FLAG", "", (x, y), power=True)
    else:
        s = K.Symbol("#PWR%d" % _pwr[0], POWER_LIB.get(net, "power:" + net), net, "", (x, y), power=True)
    root.symbol(s)


def anchor(net, x, y, flag=True):
    """power symbol, global label and PWR_FLAG on one short wire (the net's ERC driver;
    no flag on nets a part drives)"""
    power_symbol(net, x, y)
    root.wire((x, y), (x + (7.62 if flag else 3.81), y), net)
    root.glabel(net, x + 3.81, y, 90)
    if flag:
        power_symbol(net, x + 7.62, y, flag=True)
    seen(x + 7.62, y + 10)


def place(name, file, blk, at, page, label):
    """sheet symbol for a finished block; label(port name) -> root net"""
    pos = {}
    for net, shape, xy, ang in blk.hlabels:
        pos.setdefault(net, xy)
    sides = {"left": [], "right": [], "top": [], "bottom": []}
    for p in blk.ports:
        sides[p["side"]].append(p)
    for side in sides:
        sides[side].sort(key=lambda p: (pos[p["name"]][1], pos[p["name"]][0]))
    rows = max(len(sides["left"]), len(sides["right"]), 1)
    h = 2.54 * (rows + 2)
    pins = [(p["name"], p["shape"], side, 2.54 * (i + 1)) for side in sides for i, p in enumerate(sides[side])]
    ss = K.SheetSymbol(name, file, at, (W, h), pins, page=page)
    root.sheet(ss)
    for side in ("left", "right"):
        for p in sides[side]:
            x, y = ss.pin_xy(p["name"])
            dx, ang = (-STUB, 180) if side == "left" else (STUB, 0)
            net = label(p["name"])
            root.wire((x, y), (x + dx, y), net)
            root.label(net, x + dx, y, ang)
    seen(at[0] + W + STUB + 20, at[1] + h + 10)
    return ss


def pwr_only(base):
    """renumber only the power symbols (+base), keep the part references"""
    return lambda ref: renumber(ref, base) if ref.startswith("#") else ref


os.makedirs(os.path.join(PROJ_DIR, SHEETS), exist_ok=True)
X0, Y0 = 38.1, 38.1
if KIND == "core":
    sheets = [("Input", "input", cinput.block(), 7000), ("Supplies", "supplies", supplies.block(8), 6000),
              ("MCU", "mcu", mcu.block(8, tile=False), 3000), ("Mux", "mux", mux.block(8), 4000),
              ("Link", "link", link.block(8), 5000), ("Chain", "chain", chain.block("core"), 8000)]
    label = lambda n: n
    anchors = [("GND", True), ("+3V3", True), ("VIN", True), ("CTRL_3V3", True), ("CTRL_GND", True), ("CTRL_12V", True)]
    note = "UNITk_SDA / UNITk_SCL: TCA9548A channel k-1 = chain P(k-1). VIN = the core's XT30 input"
else:
    sheets = [("Unit", "unit", unit.block(), 1000), ("Input", "input", uinput.block(), 7000),
              ("Chain", "chain", chain.block("unit"), 8000)]
    label = lambda n: {"SDA": "SEG_SDA", "SCL": "SEG_SCL"}.get(n, n)
    anchors = [("GND", True), ("+3V3", True), ("VBUS", True), ("VIN", True)]
    note = "SEG_SDA / SEG_SCL: this unit's I2C segment (chain IN P0). +3V3 comes from the core over the chain. VIN = XT60, VBUS = unit hot-swap output"
for i, (name, fname, b, base) in enumerate(sheets):
    ss = place(name, "%s/%s.kicad_sch" % (SHEETS, fname), b, (X0 + PITCH * (i % 4), Y0 + 152.4 * (i // 4)), i + 2, label)
    b.write(os.path.join(PROJ_DIR, SHEETS, fname + ".kicad_sch"), instances=[(ss.path, pwr_only(base))], project=PROJECT)

ay = round((extent[1] + 15.24) / 1.27) * 1.27
root.text("POWER ANCHORS", X0, ay - 5.08)
for i, (net, flag) in enumerate(anchors):
    anchor(net, X0 + 38.1 * i, ay, flag=flag)
root.text(note, X0, ay + 15.24, size=1.5)

for name, wmm, hmm in PAPERS:
    if extent[0] + 10 <= wmm and extent[1] + 25 <= hmm:
        root.paper = name
        break
root.write(OUT)
print("wrote", OUT, "paper", root.paper)
if KIND == "core":                       # the MCU pin map for the firmware (same table as the MCU sheet)
    pins = os.path.join(PROJ_DIR, "..", "..", "firmware", "plane-core-pins.toml")
    with open(pins, "w") as f:
        f.write(mcu.pins_toml(mcu.mcu_nets(8, tile=False)))
    print("wrote", os.path.normpath(pins))

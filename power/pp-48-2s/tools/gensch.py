#!/usr/bin/env python3
"""Generate the PP-48-xS power plane schematic (KiCad 10, hierarchical).

usage: gensch.py [N] [out.kicad_sch]   (N slots, default 2)

The root sheet holds one sheet symbol per block (Input, Bucks, MCU, Link,
Expanders, Slot 1..N), a label at every sheet pin with the plane-wide net
name (S1_OFF, SCL2, VBUS_SNS, ...), the per-slot INA238 address ties, and
the power anchors (power symbol + PWR_FLAG). The blocks are drawn by
tools/sch/blocks/*.py on the engine in tools/sch/draw.py; the slot is ONE
file instantiated N times, references renumbered +100 per slot. The
.kicad_sch files are output, not source: edit the Python and regenerate.
Then: kicad-cli sch erc; kicad-cli sch export netlist --format kicadxml;
tools/schcheck.py against the previous netlist; pcbkit relink on the
board. See docs/adr/0002-schematic-generator-drawn-blocks.md.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from sch import kicad as K                      # noqa: E402
from sch.draw import renumber                   # noqa: E402
from sch.blocks import input as blk_input, bucks, mcu, link, expanders, slot   # noqa: E402

N = int(sys.argv[1]) if len(sys.argv) > 1 else 2
PROJ_DIR = os.path.dirname(HERE)
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(PROJ_DIR, "pp-48-%ds.kicad_sch" % N)
PROJECT = "pp-48-%ds" % N
DATE = "2026-10-24"
SHEETS = "sheets"                 # sub-sheet dir, relative to the root file
STUB = 7.62                       # wire from a sheet pin to its label
W = 50.8                          # sheet symbol width
PITCH = 88.9                      # sheet symbol pitch in x
PAPERS = [("A3", 420.0, 297.0), ("A2", 594.0, 420.0), ("A1", 841.0, 594.0), ("A0", 1189.0, 841.0)]

# INA238 address pins per slot, as the flat generator tied them: pin 1 (the
# symbol's A1) and pin 2 (A0); the slot sheet's ports carry the pin names
PIN1 = ["GND", "GND", "GND", "GND", "+3V3", "+3V3", "+3V3", "+3V3"]
PIN2 = ["GND", "+3V3", "SDA2", "SCL2"]
POWER_LIB = {"GND": "power:GND", "+3V3": "power:+3V3", "+12V": "power:+12V", "VBUS": "power:VBUS",
             "CTRL_3V3": "power:+3V3", "CTRL_GND": "power:GND"}

root = K.Sheet("Root", PROJECT, key=PROJECT + "/root", paper="A2", root=True,
               title="PP-48-%dS power plane" % N, date=DATE, rev="0.2", company="Granite",
               comments=["48 V plane, %d eighth-brick slots: LM5069-2 + INA238 per slot, OV latch, node PWR/RST/LED, STM32G0B1, isolated I2C" % N,
                         "generated by tools/gensch.py; docs/adr/0001-48v-power-plane.md, 0002-schematic-generator-drawn-blocks.md",
                         "immersion board: no wet electrolytics"])
_pwr = [9000]
extent = [0.0, 0.0]


def seen(x, y):
    extent[0] = max(extent[0], x); extent[1] = max(extent[1], y)


def power_symbol(net, x, y, flag=False):
    """power symbol (or PWR_FLAG) with its pin at (x, y)"""
    _pwr[0] += 1
    if flag:
        s = K.Symbol("#FLG%d" % _pwr[0], "power:PWR_FLAG", "PWR_FLAG", "", (x, y), power=True)
    else:
        s = K.Symbol("#PWR%d" % _pwr[0], POWER_LIB.get(net, "power:" + net), net, "", (x, y), power=True)
    root.symbol(s)


def anchor(net, x, y):
    """power symbol, global label and PWR_FLAG on one short wire: the net's
    driver for ERC (a power symbol wired to a flag alone is "pin not
    connected" to KiCad 10; the label makes it a net)"""
    power_symbol(net, x, y)
    root.wire((x, y), (x + 7.62, y), net)
    root.glabel(net, x + 3.81, y, 90)
    power_symbol(net, x + 7.62, y, flag=True)
    seen(x + 7.62, y + 10)


def side_pins(blk):
    """the block's ports per side, in drawing order (label y, then x)"""
    pos = {}
    for net, shape, xy, ang in blk.hlabels:
        pos.setdefault(net, xy)
    out = {"left": [], "right": [], "top": [], "bottom": []}
    for p in blk.ports:
        out[p["side"]].append(p)
    for side in out:
        out[side].sort(key=lambda p: (pos.get(p["name"], (0, 0))[1], pos.get(p["name"], (0, 0))[0]))
    return out


def place(name, file, blk, at, page, label):
    """sheet symbol for a finished block at (x, y); label(port) -> root net
    name, or ("power", net) for a power-symbol tie. Returns the SheetSymbol."""
    sides = side_pins(blk)
    rows = max(len(sides["left"]), len(sides["right"]), 1)
    cols = max(len(sides["top"]), len(sides["bottom"]), 0)
    w = max(W, 2.54 * (cols + 2))
    h = 2.54 * (rows + 2)
    pins = []
    for side in ("left", "right", "top", "bottom"):
        for i, p in enumerate(sides[side]):
            pins.append((p["name"], p["shape"], side, 2.54 * (i + 1)))
    ss = K.SheetSymbol(name, file, at, (w, h), pins, page=page)
    root.sheet(ss)
    for side in ("left", "right", "top", "bottom"):
        for p in sides[side]:
            x, y = ss.pin_xy(p["name"])
            dx, dy = {"left": (-STUB, 0), "right": (STUB, 0), "top": (0, -STUB), "bottom": (0, STUB)}[side]
            ang = {"left": 180, "right": 0, "top": 90, "bottom": 270}[side]
            net = label(p)
            if isinstance(net, tuple):
                root.wire((x, y), (x + dx, y + dy), net[1])
                power_symbol(net[1], x + dx, y + dy)
            else:
                root.wire((x, y), (x + dx, y + dy), net)
                root.label(net, x + dx, y + dy, ang)
    seen(at[0] + w + STUB + 20, at[1] + h + 10)
    return ss


def pwr_only(base):
    """renumber only the power symbols (+base), keep the part references"""
    return lambda ref: renumber(ref, base) if ref.startswith("#") else ref


# ---------------------------------------------------------------- core sheets
X0, Y0 = 25.4, 30.48
core = [("Input", "input", blk_input.block(N), 1000), ("Bucks", "bucks", bucks.block(N), 2000),
        ("MCU", "mcu", mcu.block(N), 3000), ("Link", "link", link.block(N), 4000),
        ("Expanders", "expanders", expanders.block(N), 5000)]
row_h = 0.0
page = 2
for i, (name, fname, blk, base) in enumerate(core):
    ss = place(name, "%s/%s.kicad_sch" % (SHEETS, fname), blk, (X0 + PITCH * i, Y0), page, lambda p: p["name"])
    row_h = max(row_h, ss.size[1])
    blk.write(os.path.join(os.path.dirname(OUT), SHEETS, fname + ".kicad_sch"),
              instances=[(ss.path, pwr_only(base))], project=PROJECT)
    page += 1

# ---------------------------------------------------------------- slots
sblk = slot.block(N)
PER_ROW = 5
y = Y0 + row_h + 30.48
paths = []
for s in range(1, N + 1):
    col, rowi = (s - 1) % PER_ROW, (s - 1) // PER_ROW
    at = (X0 + PITCH * col, y + rowi * 76.2)

    def slot_label(p, s=s):
        if p["name"] == "A1":
            return ("power", PIN1[s - 1])
        if p["name"] == "A0":
            t = PIN2[(s - 1) % 4]
            return ("power", t) if t in POWER_LIB else t
        if p["name"] in ("SDA2", "SCL2", "EXP_IRQ"):
            return p["name"]
        return "S%d_%s" % (s, p["name"])
    ss = place("Slot %d" % s, "%s/slot.kicad_sch" % SHEETS, sblk, at, page, slot_label)
    paths.append((ss.path, 100 * s))
    page += 1
sblk.write(os.path.join(os.path.dirname(OUT), SHEETS, "slot.kicad_sch"), instances=paths, project=PROJECT)

# ---------------------------------------------------------------- power anchors
ay = extent[1] + 15.24
ay = round(ay / 1.27) * 1.27
root.text("POWER ANCHORS", X0, ay - 5.08)
for i, net in enumerate(["GND", "+3V3", "+12V", "VBUS", "CTRL_3V3", "CTRL_GND"]):
    anchor(net, X0 + 38.1 * i, ay)
root.text("INA238 address pins A1 (pin 1) and A0 (pin 2) tied per slot at the slot sheet pins: address 0x40 + slot - 1", X0, ay + 15.24, size=1.5)

for name, wmm, hmm in PAPERS:
    if extent[0] + 10 <= wmm and extent[1] + 25 <= hmm:
        root.paper = name
        break
else:
    raise SystemExit("root sheet does not fit A0")
root.write(OUT)
print("wrote", OUT, "sheets", len(core) + 1, "slots", N, "paper", root.paper)
